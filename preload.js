const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  basicSettings: () => ipcRenderer.invoke('settings:basic'),
  saveSettings: (data) => ipcRenderer.invoke('settings:save', data),
  cachedLibrary: () => ipcRenderer.invoke('library:cached'),
  refresh: () => ipcRenderer.invoke('library:refresh'),
  clearNew: () => ipcRenderer.invoke('library:clearNew'),
  open: (url) => ipcRenderer.invoke('game:open', url),
  sessions: () => ipcRenderer.invoke('sessions:get'),
  onSessionEnded: (cb) => ipcRenderer.on('session:ended', (_e, s) => cb(s)),
  cacheScan: () => ipcRenderer.invoke('cache:scan'),
  cacheClean: (kind) => ipcRenderer.invoke('cache:clean', kind),
  achShowcase: () => ipcRenderer.invoke('ach:showcase'),
  onSession: (cb) => ipcRenderer.on('session:update', (_e, s) => cb(s)),
  news: () => ipcRenderer.invoke('news:get'),
  releases: () => ipcRenderer.invoke('releases:get'),
  friends: () => ipcRenderer.invoke('friends:list'),
  friendsCommon: (ids) => ipcRenderer.invoke('friends:common', ids),
  shots: (id) => ipcRenderer.invoke('shots:get', id),
  openShot: (file) => ipcRenderer.invoke('shots:open', file),
  savesInfo: (id) => ipcRenderer.invoke('saves:info', id),
  savesBackup: (id) => ipcRenderer.invoke('saves:backup', id),
  savesBackupAll: () => ipcRenderer.invoke('saves:backupAll'),
  savesRestore: (id, dir) => ipcRenderer.invoke('saves:restore', id, dir),
  savesOpen: (id) => ipcRenderer.invoke('saves:open', id),
  exportData: () => ipcRenderer.invoke('data:export'),
  importData: () => ipcRenderer.invoke('data:import'),
  saveCard: (rect, name) => ipcRenderer.invoke('card:save', rect, name),
  userGames: () => ipcRenderer.invoke('user:get'),
  setUserGame: (id, patch) => ipcRenderer.invoke('user:set', id, patch),
  diskInfo: () => ipcRenderer.invoke('disk:info'),
  epicFree: () => ipcRenderer.invoke('epic:free'),
  achCached: () => ipcRenderer.invoke('ach:cached'),
  achRefresh: () => ipcRenderer.invoke('ach:refresh'),
  achDetail: (appid) => ipcRenderer.invoke('ach:detail', appid),
  achFriends: (appid) => ipcRenderer.invoke('ach:friends', appid),
  onUnlocked: (cb) => ipcRenderer.on('ach:unlocked', (_e, d) => cb(d)),
  onAchProgress: (cb) => ipcRenderer.on('ach:progress', (_e, p) => cb(p)),
  perfSample: () => ipcRenderer.invoke('perf:sample'),
  setOverlay: (on) => ipcRenderer.invoke('overlay:set', on),
  onPerf: (cb) => ipcRenderer.on('perf:update', (_e, s) => cb(s)),
  focusStatus: () => ipcRenderer.invoke('focus:status'),
  focusStart: () => ipcRenderer.invoke('focus:start'),
  focusStop: () => ipcRenderer.invoke('focus:stop'),
  onFocus: (cb) => ipcRenderer.on('focus:update', (_e, s) => cb(s)),
  getDeals: () => ipcRenderer.invoke('deals:get'),
  cachedDeals: () => ipcRenderer.invoke('deals:cached'),
  linkEpic: () => ipcRenderer.invoke('epic:link'),
  pickLegendary: () => ipcRenderer.invoke('epic:pickLegendary'),
  importPurchases: () => ipcRenderer.invoke('steam:importPurchases'),
});
